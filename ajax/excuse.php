<?php
declare(strict_types=1);
require_once __DIR__ . '/../bootstrap/app.php';

use App\Http\ApiResponse;

\App\Bootstrap\AppBootstrap::bootApi();

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    ApiResponse::error('Method not allowed', 405);
}

$situation = trim($_POST['situation'] ?? '');
if (mb_strlen($situation) < 3) {
    ApiResponse::json(['excuse' => 'Ситуация слишком проста даже для отмазки.']);
}

// Templates — PHP generates a custom excuse based on keywords
$templates = [
    ['ключи' => ['упал','сломался','не работает','крашится'],
     'отмазки' => [
        'Скорее всего это из-за временного сбоя в квантовых флуктуациях на уровне ядра.',
        'Это произошло потому что кто-то менял конфиг в воскресенье. Не я.',
        'Проблема воспроизводится только на продакшне из-за специфики боевых данных.',
     ]],
    ['ключи' => ['медленно','долго','тормозит','лагает'],
     'отмазки' => [
        'Алгоритм оптимален. Это железо не успевает за кодом.',
        'Мы намеренно добавили задержку для лучшего UX — пользователь должен чувствовать что система работает.',
        'N+1 запрос? Это N+1 запрос к базе данных, оптимизированной под паттерн доступа реальных пользователей.',
     ]],
    ['ключи' => ['пятница','вечер','деплой','релиз'],
     'отмазки' => [
        'В пятницу деплой прошёл успешно. Всё что случилось после — уже не деплой.',
        'Мониторинг показал 100% uptime. Баги — это отдельная метрика.',
        'Ошибка произошла в период плановых технических работ которые я только что запланировал.',
     ]],
    ['ключи' => ['данные','база','sql','запрос'],
     'отмазки' => [
        'База данных вернула неожиданные данные. Это проблема данных, не кода.',
        'Миграция прошла успешно. Потеря части данных входила в план миграции.',
        'Индексы не были удалены намеренно — для обратной совместимости.',
     ]],
];

// Default excuses if no keywords match
$defaults = [
    'Это поведение полностью соответствует техническому заданию которое я интерпретирую иначе.',
    'Воспроизвести локально не удаётся, значит это проблема окружения.',
    'Я предупреждал что это нужно тестировать. В слаке. В 2020 году.',
    'Такое поведение — результат сложного взаимодействия нескольких систем. Исправить невозможно.',
    'Это легаси-код. Я его не писал. Но и трогать не стал чтобы не сломать остальное.',
    'Ошибка возникает только у пользователей которые неправильно используют продукт.',
    'Баг был известен. Просто не был занесён в трекер.',
];

$excuse = null;
$sitLower = mb_strtolower($situation);

foreach ($templates as $group) {
    foreach ($group['ключи'] as $key) {
        if (mb_strpos($sitLower, $key) !== false) {
            $excuse = $group['отмазки'][array_rand($group['отмазки'])];
            break 2;
        }
    }
}

if (!$excuse) {
    $excuse = $defaults[array_rand($defaults)];
}

ApiResponse::json(['excuse' => $excuse]);
